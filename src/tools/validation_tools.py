"""MCP tool implementations for plan validation."""
from __future__ import annotations

from langsmith import traceable

from ..validation.flow_plan import validate_plan
from ..validation.lineage import validate_table_selection


@traceable(name="validate_table_selection", run_type="tool")
def tool_validate_table_selection(connection_id: str, tables: list[str]) -> dict:
    """
    Check that all proposed tables exist in the selected database.

    Args:
        connection_id: The connection to check against.
        tables: List of table names the plan intends to use.

    Returns:
        {"ok": bool, "found": [...], "missing": [...]}
    """
    try:
        return validate_table_selection(connection_id, tables)
    except Exception as exc:
        return {"ok": False, "found": [], "missing": tables, "error": str(exc)}


@traceable(name="validate_flow_plan", run_type="tool")
def tool_validate_flow_plan(plan: dict) -> dict:
    """
    Structurally validate a flow plan generated by the LLM.

    The plan must be a dict with:
      - "nodes": list of node dicts (each with "id" and "type")
      - "edges": list of {"from": node_id, "to": node_id}

    Checks:
      - Unique node IDs
      - All referenced upstream nodes exist
      - All edge endpoints exist
      - Graph is acyclic
      - At least one output node

    Returns:
        {"ok": bool, "errors": [...]}
    """
    try:
        errors = validate_plan(plan)
        return {"ok": len(errors) == 0, "errors": errors}
    except Exception as exc:
        return {"ok": False, "errors": [f"Validation exception: {exc}"]}
