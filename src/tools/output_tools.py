"""MCP tool implementations for Flow JSON and Hyper extract generation."""
from __future__ import annotations

import os
from datetime import datetime, timezone

from langsmith import traceable

from ..outputs import flow_json, hyper_extract


@traceable(name="generate_flow_json", run_type="tool")
def tool_generate_flow_json(plan: dict, name: str | None = None) -> dict:
    """
    Serialize a validated flow plan into Flow JSON.

    The plan must have already passed validate_flow_plan.

    Args:
        plan: Validated plan dict with nodes, edges, sql, connection_id.
        name: Optional display name for the flow.

    Returns:
        {"ok": true, "flow_json": {...}}
        {"ok": false, "error": "..."}
    """
    try:
        result = flow_json.generate(plan, name=name)
        return {"ok": True, "flow_json": result}
    except Exception as exc:
        return {"ok": False, "error": str(exc)}


@traceable(name="generate_hyper_extract", run_type="tool")
def tool_generate_hyper_extract(
    rows: list[dict],
    output_filename: str | None = None,
    table_name: str = "Extract",
) -> dict:
    """
    Write query result rows to a Tableau Hyper extract (.hyper file).

    Args:
        rows: List of row dicts from sql_db_query.
        output_filename: Optional filename (default: auto-generated by timestamp).
        table_name: Hyper table name (default: Extract).

    Returns:
        {"ok": true, "path": "...", "row_count": N}
        {"ok": false, "error": "..."}

    The Hyper file is only created after confirmed successful write.
    """
    output_dir = os.getenv("HYPER_OUTPUT_DIR", "outputs/hyper")
    if not output_filename:
        ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        output_filename = f"extract_{ts}.hyper"

    output_path = os.path.join(output_dir, output_filename)
    return hyper_extract.generate_hyper(rows, output_path, table_name=table_name)
